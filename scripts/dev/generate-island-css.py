def generate_qml():
    dark = json.loads((ROOT / 'design-system/tokens/dark.flat.json').read_text())['colors']
    light = json.loads((ROOT / 'design-system/tokens/light.flat.json').read_text())['colors']
    tokens = json.loads((ROOT / 'design-system/tokens/tokens.json').read_text())
    radius = tokens['metrics']['radiusPx']
    motion = tokens['metrics']['motionMs']

    return f"""/* Generated by scripts/dev/generate-island-css.py; canonical palette unchanged. */
import QtQuick

QtObject {{
    id: theme

    property bool isDark: true

    // Surface tokens
    readonly property color surfaceIsland: isDark ? "{dark['surface.island']}" : "{light['surface.island']}"
    readonly property color surfaceRaised: isDark ? "{dark['surface.raised']}" : "{light['surface.raised']}"
    readonly property color surfaceHover: isDark ? "{dark['surface.hover']}" : "{light['surface.hover']}"
    readonly property color surfaceScrim: isDark ? "{dark['surface.scrim']}" : "{light['surface.scrim']}"

    // Text tokens
    readonly property color textPrimary: isDark ? "{dark['text.primary']}" : "{light['text.primary']}"
    readonly property color textSecondary: isDark ? "{dark['text.secondary']}" : "{light['text.secondary']}"
    readonly property color textTertiary: isDark ? "{dark['text.tertiary']}" : "{light['text.tertiary']}"

    // Accent tokens (Warm Minimalist Amber)
    readonly property color accentPrimary: isDark ? "{dark['accent.primary']}" : "{light['accent.primary']}"
    readonly property color accentHover: isDark ? "{dark['accent.hover']}" : "{light['accent.hover']}"

    // Border tokens
    readonly property color borderSubtle: isDark ? "{dark['border.subtle']}" : "{light['border.subtle']}"
    readonly property color borderFocus: isDark ? "{dark['border.focus']}" : "{light['border.focus']}"

    // Status tokens
    readonly property color statusSuccess: isDark ? "{dark['status.success']}" : "{light['status.success']}"
    readonly property color statusWarning: isDark ? "{dark['status.warning']}" : "{light['status.warning']}"
    readonly property color statusDanger: isDark ? "{dark['status.danger']}" : "{light['status.danger']}"

    // Progress tokens
    readonly property color progressTrack: isDark ? "{dark['progress.track']}" : "{light['progress.track']}"
    readonly property color progressFill: isDark ? "{dark['progress.fill']}" : "{light['progress.fill']}"

    // Geometry & Radius tokens (metrics.radiusPx)
    readonly property int radiusXs: {radius['xs']}
    readonly property int radiusSm: {radius['sm']}
    readonly property int radiusMd: {radius['md']}
    readonly property int radiusLg: {radius['lg']}
    readonly property int radiusXl: {radius['xl']}
    readonly property int radiusPanel: {radius['panel']}
    readonly property int radiusPill: {radius['pill']}

    // Motion timing tokens in milliseconds (metrics.motionMs)
    readonly property int durationInstant: {motion['instant']}
    readonly property int durationFast: {motion['fast']}
    readonly property int durationStandard: {motion['standard']}
    readonly property int durationEmphasis: {motion['emphasis']}
}}
"""


def generate():
    return generate_css()


if __name__ == '__main__':
    css_path = ROOT / 'extension/stylesheet.css'
    qml_path = ROOT / 'island-ui/qml/ThemeData.qml'
    generated_css = generate_css()
    generated_qml = generate_qml()

    if '--check' in sys.argv:
        errors = []
        if css_path.read_text() != generated_css:
            errors.append('Island CSS differs from approved theme exports')
        if qml_path.read_text() != generated_qml:
            errors.append('ThemeData.qml differs from approved theme exports')
        if errors:
            raise SystemExit('FAIL: ' + '; '.join(errors))
        print('PASS: scoped Island CSS and ThemeData.qml match approved theme exports')
    else:
        css_path.write_text(generated_css)
        qml_path.write_text(generated_qml)
        print('Generated scoped dark/light Island CSS and ThemeData.qml')
