#!/usr/bin/env python3
"""Export scoped Shell colors from the approved flat theme tokens."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
BASE = """/* Generated by scripts/dev/generate-island-css.py; canonical palette unchanged. */
.linux-island__capsule {
    border-radius: 20px;
    padding: 6px 18px;
    border: 1px solid transparent;
    box-shadow: 0 4px 14px rgba(0, 0, 0, 0.45);
}
.linux-island__preview {
    border-radius: 24px;
    padding: 2px;
    border: 1.5px solid transparent;
    box-shadow: 0 8px 28px rgba(0, 0, 0, 0.7);
}
.linux-island__label { font-size: 13px; font-weight: 600; }
.linux-island__artwork { border: 1px solid transparent; }
.linux-island__media-button { border: 0; }
.linux-island__metric-tile { border-radius: 10px; border: 1px solid transparent; }
.linux-island__metric-label { font-size: 10px; font-weight: 600; }
.linux-island__metric-value { font-size: 11px; font-weight: bold; }
.linux-island__metric-track { border-radius: 2px; }
.linux-island__metric-fill { border-radius: 2px; }
.linux-island__quick-toggle { border-radius: 10px; border: 1px solid transparent; }
.linux-island__quick-toggle-label { font-size: 11px; font-weight: 600; }
"""


def generate():
    output = [BASE]
    for name in ('dark', 'light'):
        colors = json.loads((ROOT / f'design-system/tokens/{name}.flat.json').read_text())['colors']
        root = f'.linux-island--{name}'
        rules = {
            f'{root}.linux-island__capsule': {'background-color': colors['surface.island'], 'color': colors['text.primary'], 'border-color': colors['border.subtle']},
            f'{root}.linux-island__capsule:hover': {'background-color': colors['surface.hover'], 'border-color': colors['accent.primary']},
            f'{root}.linux-island__preview': {'background-color': colors['surface.island'], 'color': colors['text.primary']},
            f'{root} .linux-island__label, {root} .linux-island__media-title': {'color': colors['text.primary']},
            f'{root} .linux-island__media-artist': {'color': colors['text.secondary']},
            f'{root} .linux-island__artwork': {'background-color': colors['surface.raised'], 'border-color': colors['border.subtle'], 'color': colors['icon.secondary']},
            f'{root} .linux-island__media-button': {'background-color': colors['control.secondary'], 'color': colors['icon.primary']},
            f'{root} .linux-island__media-button:hover': {'background-color': colors['surface.hover']},
            f'{root} .linux-island__media-button-primary': {'background-color': colors['control.primary'], 'color': colors['icon.onAccent']},
            f'{root} .linux-island__media-button-primary:hover': {'background-color': colors['control.primaryHover']},
            f'{root} .linux-island__media-button:focus': {'box-shadow': f'inset 0 0 0 2px {colors["border.focus"]}'},
            f'{root} .linux-island__beat-bar': {'background-color': colors['accent.primary']},
            f'{root} .linux-island__progress-track': {'background-color': colors['progress.track']},
            f'{root} .linux-island__progress-fill': {'background-color': colors['progress.fill']},
            f'{root} .linux-island__progress-time': {'color': colors['text.secondary']},
            f'{root} .linux-island__metric-tile': {'background-color': colors['surface.raised'], 'border-color': colors['border.subtle']},
            f'{root} .linux-island__metric-label': {'color': colors['text.tertiary']},
            f'{root} .linux-island__metric-value': {'color': colors['text.primary']},
            f'{root} .linux-island__metric-track': {'background-color': colors['progress.track']},
            f'{root} .linux-island__metric-fill': {'background-color': colors['progress.fill']},
            f'{root} .linux-island__quick-toggle': {'background-color': colors['surface.raised'], 'border-color': colors['border.subtle'], 'color': colors['text.secondary']},
            f'{root} .linux-island__quick-toggle:hover': {'background-color': colors['surface.hover']},
            f'{root} .linux-island__quick-toggle--active': {'background-color': colors['control.primary'], 'border-color': colors['control.primary'], 'color': colors['icon.onAccent']},
            f'{root} .linux-island__quick-toggle--active:hover': {'background-color': colors['control.primaryHover']},
            f'{root} .linux-island__quick-toggle-label': {'color': 'inherit'},
        }
        for selector, properties in rules.items():
            output.append(selector + ' {\n' + ''.join(f'    {key}: {value};\n' for key, value in properties.items()) + '}\n')
    return '\n'.join(output)


if __name__ == '__main__':
    path = ROOT / 'extension/stylesheet.css'
    generated = generate()
    if '--check' in sys.argv:
        if path.read_text() != generated:
            raise SystemExit('FAIL: Island CSS differs from approved theme exports')
        print('PASS: scoped Island CSS matches both approved theme exports')
    else:
        path.write_text(generated)
        print('Generated scoped dark/light Island CSS')
